"""Export the memory graph as a Mermaid diagram (.md) and a standalone HTML page."""

from __future__ import annotations

import html
from pathlib import Path

from .paths import ensure_outside_repo, exports_dir
from .store import MemoryStore

TYPE_COLORS = {
    "person": "#f4a261", "organization": "#2a9d8f", "project": "#457b9d", "decision": "#e76f51",
    "fact": "#8d99ae", "task": "#e9c46a", "document": "#a8dadc", "preference": "#cdb4db",
    "application": "#90be6d", "skill": "#bde0fe",
}
MERMAID_CDN = "https://cdn.jsdelivr.net/npm/mermaid@10.9.1/dist/mermaid.esm.min.mjs"


def _label(text: str) -> str:
    text = " ".join(text.split())
    return text.replace('"', "#quot;").replace("<", "#lt;").replace(">", "#gt;")


def to_mermaid(store: MemoryStore, include_superseded: bool = False) -> str:
    nodes = store.all_nodes(include_superseded)
    ids = {n.id for n in nodes}
    lines = ["flowchart LR"]
    for n in nodes:
        lines.append(f'    n{n.id}["{_label(n.name)}<br/>({n.type})"]:::{n.type}')
    for e in store.all_edges(include_superseded):
        if e.src in ids and e.dst in ids:
            arrow = "-.->" if e.relation == "supersedes" else "-->"
            lines.append(f"    n{e.src} {arrow}|{e.relation}| n{e.dst}")
    for t, color in TYPE_COLORS.items():
        lines.append(f"    classDef {t} fill:{color},stroke:#333,color:#111")
    return "\n".join(lines)


def to_markdown(store: MemoryStore) -> str:
    nodes, edges = len(store.all_nodes()), len(store.all_edges())
    return (
        "# Memory graph\n\n"
        f"{nodes} active nodes, {edges} edges between them. Generated by `room graph`.\n\n"
        f"```mermaid\n{to_mermaid(store)}\n```\n"
    )


def to_html(store: MemoryStore) -> str:
    diagram = html.escape(to_mermaid(store))
    rows = "\n".join(
        f"<tr><td>{html.escape(n.name)}</td><td>{html.escape(n.type)}</td><td>{html.escape(n.summary)}</td></tr>"
        for n in store.all_nodes()
    )
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Memory Graph</title>
<style>
  :root {{ --bg: #ffffff; --fg: #1d1d1f; --muted: #6e6e73; --line: #d2d2d7; }}
  @media (prefers-color-scheme: dark) {{ :root {{ --bg: #111214; --fg: #f2f2f2; --muted: #a1a1a6; --line: #333; }} }}
  body {{ margin: 0; padding: 24px 16px; background: var(--bg); color: var(--fg);
         font: 15px/1.5 -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif; }}
  main {{ max-width: 1100px; margin: 0 auto; }}
  .diagram {{ overflow-x: auto; border: 1px solid var(--line); border-radius: 8px; padding: 12px; background: #fff; }}
  table {{ width: 100%; border-collapse: collapse; margin-top: 24px; font-size: 14px; }}
  th, td {{ text-align: left; padding: 6px 8px; border-bottom: 1px solid var(--line); vertical-align: top; }}
  th {{ color: var(--muted); font-weight: 600; }}
  p {{ color: var(--muted); }}
</style>
</head>
<body>
<main>
<h1>Memory graph</h1>
<p>Generated by <code>room graph</code>. The diagram needs internet access to load Mermaid; the table below works offline.</p>
<div class="diagram"><pre class="mermaid">
{diagram}
</pre></div>
<table>
<thead><tr><th>Name</th><th>Type</th><th>Summary</th></tr></thead>
<tbody>
{rows}
</tbody>
</table>
</main>
<script type="module">
  import mermaid from "{MERMAID_CDN}";
  mermaid.initialize({{ startOnLoad: true, securityLevel: "strict" }});
</script>
</body>
</html>
"""


def write_graph(store: MemoryStore, out: Path | None = None) -> tuple[Path, Path]:
    """Write <out>.md and <out>.html (default ~/.agent-room/exports/graph.*).

    Exports of real memory may not be written inside the repository; exports
    of the made-up demo database may (that is how the README diagram is made).
    """
    base = Path(out).expanduser() if out else exports_dir() / "graph"
    md_path, html_path = base.with_suffix(".md"), base.with_suffix(".html")
    if not store.is_demo:
        ensure_outside_repo(md_path)
        ensure_outside_repo(html_path)
    md_path.parent.mkdir(parents=True, exist_ok=True)
    md_path.write_text(to_markdown(store), encoding="utf-8")
    html_path.write_text(to_html(store), encoding="utf-8")
    return md_path, html_path
